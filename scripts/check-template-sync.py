# check-template-sync - fail when projects/template is not what
# scripts/new-project generates.
#
# Decision K9 puts the skeleton in scripts/new-project: the script is the single
# place that defines what a new project looks like, and projects/template is the
# same skeleton kept in the tree so that it can be read (and so that the docs
# have something to point at). Two copies of one thing drift, and these did -
# when 4.2 started the template had no resources/ and its main.cpp had six
# differences from the script's - so the copy is verified now instead of
# trusted.
#
# The check runs the real generator, `scripts/new-project qxtemplate`, into a
# temporary directory and compares the result with projects/template byte for
# byte. Running the script rather than reading its constants means a bug in the
# generator itself is caught here too.
#
# README.md is the one file that is deliberately different, and it is excluded
# by name: the script writes the README of a generated project, addressed to
# whoever owns that project, while projects/template/README.md is addressed to
# whoever is reading this repository - it says how to install the SDK out of
# this checkout and what the directory is for. Both are wanted and neither
# substitutes for the other.
#
# Usage:
#   python3 scripts/check-template-sync.py            # check; non-zero on drift
#   python3 scripts/check-template-sync.py --update   # rewrite the template

import argparse
import difflib
import filecmp
import os
import shutil
import subprocess
import sys
import tempfile

SCRIPT_DIR = os.path.dirname(os.path.realpath(__file__))
ROOT_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, os.pardir))
NEW_PROJECT = os.path.join(SCRIPT_DIR, "new-project")
TEMPLATE_DIR = os.path.join(ROOT_DIR, "projects", "template")

# The name the template is rendered with. It has to be one the script accepts,
# and it is the name the template has always given itself.
TEMPLATE_NAME = "qxtemplate"

# See the header. A tuple so that a second exception has to be added on purpose.
EXCLUDED = ("README.md",)


def relative_files(directory):
    """Every file under directory, as sorted paths relative to it."""
    found = []
    for parent, dirs, names in os.walk(directory):
        dirs.sort()
        for name in sorted(names):
            path = os.path.join(parent, name)
            found.append(os.path.relpath(path, directory).replace(os.sep, "/"))
    return sorted(found)


def render(destination):
    """Run the scaffolding script and return the tree it produced."""
    subprocess.run(
        [sys.executable, NEW_PROJECT, TEMPLATE_NAME, "-o", destination],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    return os.path.join(destination, TEMPLATE_NAME)


def unified_diff(generated, template, relative):
    """A diff from what the script writes to what the template has."""
    try:
        with open(generated, encoding="utf-8") as handle:
            left = handle.readlines()
        with open(template, encoding="utf-8") as handle:
            right = handle.readlines()
    except UnicodeDecodeError:
        return "      (binary file)\n"
    return "".join(
        difflib.unified_diff(
            left,
            right,
            fromfile="scripts/new-project -> " + relative,
            tofile="projects/template/" + relative,
        )
    )


def main():
    parser = argparse.ArgumentParser(
        description="check that projects/template is what scripts/new-project generates",
    )
    parser.add_argument(
        "--update",
        action="store_true",
        help="rewrite the template from the generator instead of only reporting",
    )
    args = parser.parse_args()

    with tempfile.TemporaryDirectory(prefix="qtcanpool-template-") as work:
        generated = render(work)
        expected = [p for p in relative_files(generated) if p not in EXCLUDED]
        present = [p for p in relative_files(TEMPLATE_DIR) if p not in EXCLUDED]

        if args.update:
            for relative in expected:
                target = os.path.join(TEMPLATE_DIR, relative)
                os.makedirs(os.path.dirname(target), exist_ok=True)
                shutil.copyfile(os.path.join(generated, relative), target)
                print("wrote projects/template/" + relative)
            # Never deletes: an unexpected file is reported so that removing it
            # stays a deliberate act.
            for relative in present:
                if relative not in expected:
                    print("stale: projects/template/%s is not generated by the script"
                          % relative)
            return 0

        problems = []
        for relative in expected:
            source = os.path.join(generated, relative)
            target = os.path.join(TEMPLATE_DIR, relative)
            if not os.path.isfile(target):
                problems.append(("missing", relative))
            elif not filecmp.cmp(source, target, shallow=False):
                problems.append(("differs", relative))
        for relative in present:
            if relative not in expected:
                problems.append(("extra", relative))

        if problems:
            print("projects/template has drifted from scripts/new-project:",
                  file=sys.stderr)
            for kind, relative in problems:
                if kind == "missing":
                    print("  missing  projects/template/%s (the script writes it)"
                          % relative, file=sys.stderr)
                elif kind == "extra":
                    print("  extra    projects/template/%s (the script does not write it)"
                          % relative, file=sys.stderr)
                else:
                    print("  differs  projects/template/%s" % relative, file=sys.stderr)
                    print(unified_diff(os.path.join(generated, relative),
                                       os.path.join(TEMPLATE_DIR, relative), relative),
                          file=sys.stderr)
            print("\nRun 'python3 scripts/check-template-sync.py --update' to rewrite the"
                  "\ntemplate from the script, or change the script if the template is right.",
                  file=sys.stderr)
            return 1

        print("projects/template matches scripts/new-project (%d file(s))"
              % len(expected))
        return 0


if __name__ == "__main__":
    sys.exit(main())
